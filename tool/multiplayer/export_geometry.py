"""Export precisely the collision geometry used by the TypeScript module."""
import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET
root = Path(__file__).resolve().parents[2]
raw = (root / 'assets/tiles/maptile.tmx').read_bytes()
tree = ET.fromstring(raw)
w = int(tree.attrib['width']) * int(tree.attrib['tilewidth'])
h = int(tree.attrib['height']) * int(tree.attrib['tileheight'])
maps = {}
hashes = {}
# The current deployed server identifies Survival rooms with one TMX hash.
# Accept it only when the selected map still matches its deployed collision.
deployed_hash = 'efb354fae890bd2ab382718e49018fb9571fc6d1d2f7ef484fab6ccaa8f7503f'
deployed_layouts = {
    'breach': '98a12dbf932fe96449a332e179a3ed9c6c2c8ada28f776962aebeb4c33b1ded2',
    'foundry': 'c39954b92f295bacddb69db664a5c68e62fb95a6eb6d420c3d6af5b055be5e48',
    'floodworks': 'dff8a0855b3aa1bab65a02dc0abbd971773574ba3a8020af1c8a8f3251920612',
    'relayGraveyard': '5727d047f39e7e5f7e603058a628fd743f7641e685fb67cc5c2053c7283df986',
}
legacy = {}
for name in deployed_layouts:
    obstacles = []
    objects = tree.find(f"objectgroup[@name='{name}_obstacles']").findall('object')
    if name == 'floodworks':
        objects += tree.find("objectgroup[@name='floodworks_gate']").findall('object')
    for obj in objects:
        x = float(obj.attrib['x']) - w / 2
        y = float(obj.attrib['y']) - h / 2
        obstacles.append([x, y, x + float(obj.attrib['width']), y + float(obj.attrib['height'])])
    geometry = {'bounds': [-w / 2, -h / 2, w / 2, h / 2], 'obstacles': obstacles}
    maps[name] = geometry
    hashes[name] = hashlib.sha256(json.dumps(geometry, separators=(',', ':')).encode()).hexdigest()
    if hashes[name] == deployed_layouts[name]:
        legacy[name] = deployed_hash
maps['network_lab'] = {'bounds': [-1000.0,-700.0,1000.0,700.0], 'obstacles': []}
# Dedicated competitive variants share one authored source with the server.
pack = {}
for path in sorted((root/'assets/tiles/multiplayer').glob('*.tmx')):
    raw_map=path.read_bytes(); m=ET.fromstring(raw_map)
    props={p.attrib['name']:p.attrib['value'] for p in m.find('properties')}
    mw=int(m.attrib['width'])*int(m.attrib['tilewidth']);mh=int(m.attrib['height'])*int(m.attrib['tileheight'])
    def objects(name):
        return [(float(o.attrib['x'])-mw/2,float(o.attrib['y'])-mh/2,float(o.attrib['width']),float(o.attrib['height'])) for o in m.find(f"objectgroup[@name='{name}']").findall('object')]
    map_id=props['mapId'];hashes[map_id]=hashlib.sha256(raw_map).hexdigest()
    pack[map_id]={'bounds':[-mw/2,-mh/2,mw/2,mh/2], 'obstacles':[[x,y,x+w,y+h] for x,y,w,h in objects('solids')],
        'spawns':[[[x,y]for x,y,_,_ in objects(f'team_{team}')]for team in range(2)],
        'sockets':[[x,y]for x,y,_,_ in objects('ai_sockets')], 'routes':[[x,y]for x,y,_,_ in objects('routes')],
        'title':props['title'],'material':props['material'],'teamSize':int(props['teamSize']),
        'contentVersion':int(props['contentVersion']),'stage':props['stage'],'hash':hashes[map_id]}
manifest={'schema':1,'maps':pack}
(root/'assets/tiles/multiplayer/maps.json').write_text(json.dumps(manifest,indent=2)+'\n')
maps.update(pack)
(root / 'lib/multiplayer/geometry.dart').write_text(
    '// Generated by tool/multiplayer/export_geometry.py; do not edit.\n'
    f"const geometryHash = '{hashlib.sha256(raw).hexdigest()}';\n"
    'const geometryHashes = '+json.dumps(hashes,indent=2)+';\n'
    'const legacyGeometryHashes = '+json.dumps(legacy,indent=2)+';\n'
    'const onlineGeometry = ' + json.dumps(maps, indent=2) + ';\n')
